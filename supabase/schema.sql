-- Ichiro Sushiya · base de datos (Supabase)
--
-- Se corre una sola vez, completo, en Supabase → SQL Editor. Crea las tablas, las reglas
-- de los pedidos y carga la carta actual (la del Canva).
--
-- Seguridad: todas las tablas tienen RLS activado y SIN políticas, así que con la clave
-- pública (anon) no se puede leer ni escribir nada. Solo el Worker de Cloudflare entra,
-- con la clave secreta (service_role), y él decide qué se muestra y quién administra.
--
-- Turnos:
--   mediodia  lunes a viernes: pokes. Un producto se puede pedir un día solo si está
--             cargado en `disponibilidad` para ese día (los «pokes del día»).
--   finde     sábados y domingos a la noche: sushi y demás. Se puede pedir todo lo que
--             esté activo; si para ese día tiene stock cargado, no se pasa de ese número.

set search_path = public;

-- ---------------------------------------------------------------- Tablas

create table categorias (
  id      bigint generated by default as identity primary key,
  nombre  text    not null check (length(btrim(nombre)) between 1 and 60),
  jp      text    not null default '' check (length(jp) <= 20),
  turno   text    not null check (turno in ('mediodia', 'finde')),
  orden   integer not null default 0,
  activa  boolean not null default true
);

create table productos (
  id            bigint generated by default as identity primary key,
  categoria_id  bigint  not null references categorias (id) on delete restrict,
  nombre        text    not null check (length(btrim(nombre)) between 1 and 80),
  descripcion   text    not null default '' check (length(descripcion) <= 300),
  precio        integer not null check (precio >= 0),
  activo        boolean not null default true,
  orden         integer not null default 0,
  foto          text    not null default '' check (length(foto) <= 500)   -- dirección pública en Storage
);
create index productos_categoria on productos (categoria_id);

-- Stock por día. stock null = sin límite. vendidos lo suman los pedidos y lo devuelven
-- los rechazados o cancelados.
create table disponibilidad (
  fecha        date    not null,
  producto_id  bigint  not null references productos (id) on delete cascade,
  stock        integer check (stock is null or stock >= 0),
  vendidos     integer not null default 0 check (vendidos >= 0),
  primary key (fecha, producto_id)
);

create table ajustes (
  clave  text primary key,
  valor  jsonb not null
);

create table pedidos (
  id          bigint generated always as identity primary key,
  creado      timestamptz not null default now(),
  actualizado timestamptz not null default now(),
  nombre      text    not null,
  telefono    text    not null,
  fecha       date    not null,
  turno       text    not null check (turno in ('mediodia', 'finde')),
  horario     text    not null,
  modalidad   text    not null check (modalidad in ('retiro', 'envio')),
  direccion   text    not null default '',
  notas       text    not null default '',
  items       jsonb   not null,           -- [{id, nombre, categoria, precio, cantidad}] como estaban al pedir
  subtotal    integer not null,
  envio       integer not null default 0,
  total       integer not null,
  estado      text    not null default 'pendiente'
              check (estado in ('pendiente', 'confirmado', 'entregado', 'rechazado', 'cancelado'))
);
create index pedidos_estado_fecha on pedidos (estado, fecha);
create index pedidos_fecha on pedidos (fecha);

alter table categorias     enable row level security;
alter table productos      enable row level security;
alter table disponibilidad enable row level security;
alter table ajustes        enable row level security;
alter table pedidos        enable row level security;

revoke all on categorias, productos, disponibilidad, ajustes, pedidos from anon, authenticated;
grant all on categorias, productos, disponibilidad, ajustes, pedidos to service_role;

-- ---------------------------------------------------------------- Funciones de apoyo

-- Hoy y ahora en Argentina
create function hoy_ar() returns date language sql stable as $$
  select (now() at time zone 'America/Argentina/Buenos_Aires')::date
$$;

-- Lunes a viernes → mediodia; sábado y domingo → finde
create function turno_de(f date) returns text language sql immutable as $$
  select case when extract(isodow from f) between 1 and 5 then 'mediodia' else 'finde' end
$$;

create function ajuste(c text) returns jsonb language sql stable as $$
  select valor from ajustes where clave = c
$$;

-- Lo que se puede mostrar en la web (nunca el mail de avisos)
create function ajustes_publicos() returns jsonb language sql stable as $$
  select coalesce(jsonb_object_agg(clave, valor), '{}'::jsonb)
  from ajustes
  where clave in ('pedidos_mediodia', 'pedidos_finde', 'franjas_mediodia', 'franjas_finde',
                  'dias_adelante', 'anticipacion_horas', 'costo_envio', 'whatsapp', 'instagram',
                  'textos', 'aviso')
$$;

-- ---------------------------------------------------------------- La carta para la web

-- Categorías y productos activos, los ajustes públicos y, para cada uno de los próximos
-- días, si se puede pedir y cuánto queda de cada producto.
create function carta_publica() returns jsonb language plpgsql stable as $$
declare
  v_hoy   date := hoy_ar();
  v_dias  int  := least(greatest(coalesce((ajuste('dias_adelante'))::int, 7), 0), 30);
begin
  return jsonb_build_object(
    'hoy', v_hoy,
    'ajustes', ajustes_publicos(),
    'categorias', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', c.id, 'nombre', c.nombre, 'jp', c.jp, 'turno', c.turno,
               'productos', coalesce((
                 select jsonb_agg(jsonb_build_object('id', p.id, 'nombre', p.nombre,
                                                     'descripcion', p.descripcion, 'precio', p.precio,
                                                     'foto', p.foto)
                                  order by p.orden, p.id)
                 from productos p where p.categoria_id = c.id and p.activo), '[]'::jsonb))
             order by c.orden, c.id)
      from categorias c where c.activa), '[]'::jsonb),
    'dias', coalesce((
      select jsonb_agg(jsonb_build_object(
               'fecha', d.f,
               'turno', turno_de(d.f),
               'abierto', coalesce((ajuste('pedidos_' || turno_de(d.f)))::boolean, false),
               -- producto → lo que queda (null = sin límite). En mediodía solo aparecen los cargados.
               'quedan', coalesce((
                 select jsonb_object_agg(x.producto_id::text,
                          case when x.stock is null then null else greatest(x.stock - x.vendidos, 0) end)
                 from disponibilidad x where x.fecha = d.f), '{}'::jsonb))
             order by d.f)
      from (select g::date as f from generate_series(v_hoy, v_hoy + v_dias, interval '1 day') g) d), '[]'::jsonb)
  );
end $$;

-- ---------------------------------------------------------------- Crear un pedido

-- Recibe {nombre, telefono, fecha, horario, modalidad, direccion, notas, items:[{id, cantidad}]}.
-- Los precios salen de la base, nunca del navegador. Descuenta el stock en el momento,
-- así dos personas no se llevan el último. Los errores salen con un mensaje para el cliente.
create function crear_pedido(p jsonb) returns jsonb language plpgsql as $$
declare
  tz           constant text := 'America/Argentina/Buenos_Aires';
  v_nombre     text := btrim(coalesce(p->>'nombre', ''));
  v_telefono   text := regexp_replace(coalesce(p->>'telefono', ''), '[^0-9+]', '', 'g');
  v_horario    text := btrim(coalesce(p->>'horario', ''));
  v_modalidad  text := coalesce(p->>'modalidad', '');
  v_direccion  text := btrim(coalesce(p->>'direccion', ''));
  v_notas      text := btrim(coalesce(p->>'notas', ''));
  v_fecha      date;
  v_turno      text;
  v_hoy        date := hoy_ar();
  v_items      jsonb := '[]'::jsonb;
  v_subtotal   int := 0;
  v_envio      int := 0;
  v_pedido     pedidos;
  r            record;
  v_prod       record;
begin
  if length(v_nombre) < 2 or length(v_nombre) > 80 then
    raise exception 'Escribí tu nombre';
  end if;
  if length(regexp_replace(v_telefono, '\D', '', 'g')) not between 8 and 15 then
    raise exception 'Revisá el teléfono: tiene que tener el código de área';
  end if;
  if v_modalidad not in ('retiro', 'envio') then
    raise exception 'Elegí si lo retirás o te lo enviamos';
  end if;
  if v_modalidad = 'envio' and length(v_direccion) < 5 then
    raise exception 'Escribí la dirección de entrega';
  end if;
  if length(v_direccion) > 200 or length(v_notas) > 300 then
    raise exception 'La dirección o las notas son demasiado largas';
  end if;

  begin
    v_fecha := (p->>'fecha')::date;
  exception when others then
    raise exception 'Elegí el día';
  end;
  if v_fecha is null then raise exception 'Elegí el día'; end if;
  v_turno := turno_de(v_fecha);

  if not coalesce((ajuste('pedidos_' || v_turno))::boolean, false) then
    raise exception '%', case v_turno when 'mediodia' then 'Los pedidos de pokes están cerrados por ahora'
                                      else 'Los pedidos del finde están cerrados por ahora' end;
  end if;
  if v_fecha < v_hoy or v_fecha > v_hoy + coalesce((ajuste('dias_adelante'))::int, 7) then
    raise exception 'Ese día no se puede pedir todavía';
  end if;
  if not coalesce(ajuste('franjas_' || v_turno), '[]'::jsonb) ? v_horario then
    raise exception 'Elegí un horario de la lista';
  end if;
  if ((v_fecha + v_horario::time) at time zone tz)
     < now() + make_interval(hours => coalesce((ajuste('anticipacion_horas'))::int, 0)) then
    raise exception 'Ese horario ya pasó o está muy cerca: elegí uno más tarde';
  end if;

  -- Los productos, juntando repetidos
  for r in
    select (e->>'id')::bigint as id, sum((e->>'cantidad')::int) as cant
    from jsonb_array_elements(coalesce(p->'items', '[]'::jsonb)) e
    group by 1
    order by 1          -- siempre en el mismo orden: evita bloqueos cruzados entre pedidos
  loop
    if r.cant is null or r.cant < 1 or r.cant > 50 then
      raise exception 'Revisá las cantidades del pedido';
    end if;

    select pr.id, pr.nombre, pr.precio, c.nombre as categoria, c.turno into v_prod
    from productos pr join categorias c on c.id = pr.categoria_id
    where pr.id = r.id and pr.activo and c.activa;
    if not found then
      raise exception 'Uno de los productos ya no está en la carta: actualizá la página';
    end if;
    if v_prod.turno <> v_turno then
      raise exception '%', format('%s %s se pide %s', v_prod.categoria, v_prod.nombre,
        case v_prod.turno when 'mediodia' then 'de lunes a viernes al mediodía' else 'los sábados y domingos' end);
    end if;

    if v_turno = 'mediodia' then
      update disponibilidad set vendidos = vendidos + r.cant
      where fecha = v_fecha and producto_id = r.id and (stock is null or vendidos + r.cant <= stock);
    else
      insert into disponibilidad as d (fecha, producto_id, vendidos) values (v_fecha, r.id, r.cant)
      on conflict (fecha, producto_id) do update set vendidos = d.vendidos + excluded.vendidos
      where d.stock is null or d.vendidos + excluded.vendidos <= d.stock;
    end if;
    if not found then
      raise exception '%', format('No alcanza el stock de %s %s para ese día', v_prod.categoria, v_prod.nombre);
    end if;

    v_items := v_items || jsonb_build_object('id', v_prod.id, 'nombre', v_prod.nombre,
                 'categoria', v_prod.categoria, 'precio', v_prod.precio, 'cantidad', r.cant);
    v_subtotal := v_subtotal + v_prod.precio * r.cant;
  end loop;

  if jsonb_array_length(v_items) = 0 then
    raise exception 'El pedido está vacío';
  end if;

  if v_modalidad = 'envio' then
    v_envio := greatest(coalesce((ajuste('costo_envio'))::int, 0), 0);
  end if;

  insert into pedidos (nombre, telefono, fecha, turno, horario, modalidad, direccion, notas,
                       items, subtotal, envio, total)
  values (v_nombre, v_telefono, v_fecha, v_turno, v_horario, v_modalidad,
          case when v_modalidad = 'envio' then v_direccion else '' end, v_notas,
          v_items, v_subtotal, v_envio, v_subtotal + v_envio)
  returning * into v_pedido;

  return to_jsonb(v_pedido);
end $$;

-- ---------------------------------------------------------------- Panel: estados y stock

-- Cambia el estado. Al rechazar o cancelar devuelve el stock. Un pedido rechazado o
-- cancelado ya no se puede reabrir (el stock pudo haberse vendido a otro).
create function cambiar_estado(p_id bigint, p_estado text) returns jsonb language plpgsql as $$
declare
  v pedidos;
  it jsonb;
begin
  if p_estado not in ('pendiente', 'confirmado', 'entregado', 'rechazado', 'cancelado') then
    raise exception 'Estado desconocido';
  end if;
  select * into v from pedidos where id = p_id for update;
  if not found then raise exception 'No encontré el pedido'; end if;
  if v.estado in ('rechazado', 'cancelado') and p_estado <> v.estado then
    raise exception 'Ese pedido ya está %: no se puede reabrir', v.estado;
  end if;

  if p_estado in ('rechazado', 'cancelado') and v.estado not in ('rechazado', 'cancelado') then
    for it in select * from jsonb_array_elements(v.items) loop
      update disponibilidad set vendidos = greatest(vendidos - (it->>'cantidad')::int, 0)
      where fecha = v.fecha and producto_id = (it->>'id')::bigint;
    end loop;
  end if;

  update pedidos set estado = p_estado, actualizado = now() where id = p_id returning * into v;
  return to_jsonb(v);
end $$;

-- El día visto desde el panel: los productos del turno de esa fecha con su stock.
create function dia_admin(p_fecha date) returns jsonb language sql stable as $$
  select jsonb_build_object(
    'fecha', p_fecha,
    'turno', turno_de(p_fecha),
    'productos', coalesce(jsonb_agg(jsonb_build_object(
        'id', pr.id, 'nombre', pr.nombre, 'categoria', c.nombre, 'activo', pr.activo and c.activa,
        'cargado', d.producto_id is not null, 'stock', d.stock, 'vendidos', coalesce(d.vendidos, 0))
      order by c.orden, c.id, pr.orden, pr.id), '[]'::jsonb))
  from productos pr
  join categorias c on c.id = pr.categoria_id
  left join disponibilidad d on d.producto_id = pr.id and d.fecha = p_fecha
  where c.turno = turno_de(p_fecha)
$$;

-- Guarda el día: filas [{id, cargado, stock}]. stock null = sin límite.
-- Sacar un producto que ya tiene vendidos lo deja con stock = vendidos (no se vende más).
create function guardar_dia(p_fecha date, p_filas jsonb) returns jsonb language plpgsql as $$
declare
  f jsonb;
  v_id bigint;
  v_stock int;
begin
  for f in select * from jsonb_array_elements(p_filas) loop
    v_id := (f->>'id')::bigint;
    v_stock := nullif(f->>'stock', '')::int;
    if v_stock is not null and v_stock < 0 then raise exception 'El stock no puede ser negativo'; end if;

    if coalesce((f->>'cargado')::boolean, false) then
      insert into disponibilidad as d (fecha, producto_id, stock) values (p_fecha, v_id, v_stock)
      on conflict (fecha, producto_id) do update set stock = excluded.stock;
    else
      delete from disponibilidad where fecha = p_fecha and producto_id = v_id and vendidos = 0;
      update disponibilidad set stock = vendidos where fecha = p_fecha and producto_id = v_id;
    end if;
  end loop;
  return dia_admin(p_fecha);
end $$;

-- Copia los pokes (y su stock) de un día a otro: para no cargarlos a mano cada día.
create function copiar_dia(p_desde date, p_hasta date) returns jsonb language plpgsql as $$
begin
  if turno_de(p_desde) <> turno_de(p_hasta) then
    raise exception 'Solo se puede copiar entre días del mismo turno';
  end if;
  insert into disponibilidad as d (fecha, producto_id, stock)
  select p_hasta, producto_id, stock from disponibilidad where fecha = p_desde
  on conflict (fecha, producto_id) do update set stock = excluded.stock;
  return dia_admin(p_hasta);
end $$;

